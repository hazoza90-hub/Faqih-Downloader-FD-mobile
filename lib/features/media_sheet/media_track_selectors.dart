import 'package:flutter/material.dart';

import '../../core/i18n/translator.dart';
import '../../core/models/audio_track.dart';
import '../../core/models/subtitle_track.dart';
import '../../core/theme/app_colors.dart';
import '../../services/coordinator/download_job_models.dart';

/// Dubbing / audio track and subtitle track + embed mode selector widgets.
class MediaTrackSelectors extends StatelessWidget {
  const MediaTrackSelectors({
    super.key,
    required this.translator,
    required this.audioTracks,
    required this.selectedAudio,
    required this.onAudioSelected,
    required this.subtitleTracks,
    required this.selectedSubtitle,
    required this.subtitleMode,
    required this.audioOnly,
    required this.onSubtitleSelected,
    required this.onSubtitleModeChanged,
    this.onPickExternalSubtitle,
  });

  final AppTranslator translator;
  final List<AudioTrack> audioTracks;
  final AudioTrack? selectedAudio;
  final void Function(AudioTrack track) onAudioSelected;
  final List<SubtitleTrack> subtitleTracks;
  final SubtitleTrack? selectedSubtitle;
  final SubtitleMode subtitleMode;
  final bool audioOnly;
  final void Function(SubtitleTrack? track) onSubtitleSelected;
  final void Function(SubtitleMode mode) onSubtitleModeChanged;
  final VoidCallback? onPickExternalSubtitle;

  @override
  Widget build(BuildContext context) {
    final tr = translator.tr;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: <Widget>[
        if (audioTracks.isNotEmpty) ...<Widget>[
          const SizedBox(height: 12),
          Text(
            tr('lbl_dubbing'),
            style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w600),
          ),
          const SizedBox(height: 6),
          Wrap(
            spacing: 6,
            runSpacing: 6,
            children: audioTracks.map((track) {
              final selected = selectedAudio?.trackId == track.trackId &&
                  selectedAudio?.formatId == track.formatId;
              final tag = track.isOriginal ? tr('badge_original') : tr('badge_dubbed');
              final kbps = track.bitrateKbps > 0 ? ' • ${track.bitrateKbps}k' : '';
              return ChoiceChip(
                key: Key('audio_track_${track.trackId}'),
                label: Text('${track.language.toUpperCase()} ($tag)$kbps'),
                selected: selected,
                onSelected: (_) => onAudioSelected(track),
              );
            }).toList(growable: false),
          ),
        ],
        if (!audioOnly && (subtitleTracks.isNotEmpty || onPickExternalSubtitle != null)) ...<Widget>[
          const SizedBox(height: 12),
          Text(
            tr('lbl_subtitles'),
            style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w600),
          ),
          const SizedBox(height: 6),
          Wrap(
            spacing: 6,
            runSpacing: 6,
            children: <Widget>[
              ChoiceChip(
                key: const Key('sub_track_none'),
                label: Text(tr('lbl_no_subtitle')),
                selected: selectedSubtitle == null,
                onSelected: (_) => onSubtitleSelected(null),
              ),
              ...subtitleTracks.map((sub) {
                final selected = selectedSubtitle?.subId == sub.subId;
                final origin = sub.isExternal
                    ? tr('badge_external_sub')
                    : (sub.isAutoGenerated
                        ? tr('badge_auto_caption')
                        : tr('badge_manual_caption'));
                final titlePrefix = sub.isExternal && sub.label.isNotEmpty
                    ? sub.label
                    : sub.language.toUpperCase();
                return ChoiceChip(
                  key: Key('sub_track_${sub.subId}'),
                  label: Text('$titlePrefix • $origin'),
                  selected: selected,
                  onSelected: (_) => onSubtitleSelected(sub),
                );
              }),
            ],
          ),
          if (onPickExternalSubtitle != null) ...<Widget>[
            const SizedBox(height: 8),
            OutlinedButton.icon(
              key: const Key('pick_external_subtitle_btn'),
              onPressed: onPickExternalSubtitle,
              icon: const Icon(Icons.subtitles_outlined, size: 17),
              label: Text(tr('btn_pick_external_sub')),
            ),
          ],
          if (selectedSubtitle != null) ...<Widget>[
            const SizedBox(height: 10),
            Text(
              tr('lbl_subtitle_mode'),
              style: const TextStyle(fontSize: 12, color: AppColors.textSecondary),
            ),
            const SizedBox(height: 6),
            Wrap(
              spacing: 6,
              children: <Widget>[
                ChoiceChip(
                  key: const Key('sub_mode_none'),
                  label: Text(tr('sub_mode_none')),
                  selected: subtitleMode == SubtitleMode.none,
                  onSelected: (_) => onSubtitleModeChanged(SubtitleMode.none),
                ),
                ChoiceChip(
                  key: const Key('sub_mode_soft'),
                  label: Text(tr('sub_mode_soft')),
                  selected: subtitleMode == SubtitleMode.softMux,
                  onSelected: (_) => onSubtitleModeChanged(SubtitleMode.softMux),
                ),
                ChoiceChip(
                  key: const Key('sub_mode_hard'),
                  label: Text(tr('sub_mode_hard')),
                  selected: subtitleMode == SubtitleMode.hardBurn,
                  onSelected: (_) => onSubtitleModeChanged(SubtitleMode.hardBurn),
                ),
              ],
            ),
          ],
        ],
      ],
    );
  }
}
