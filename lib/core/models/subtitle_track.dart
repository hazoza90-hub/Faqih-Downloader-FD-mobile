import 'package:flutter/foundation.dart';

/// Selectable built-in or external subtitle track for video downloads.
@immutable
class SubtitleTrack {
  const SubtitleTrack({
    required this.subId,
    required this.language,
    required this.label,
    required this.url,
    this.ext = 'srt',
    this.isAutoGenerated = false,
    this.isExternal = false,
    this.localPath,
  });

  final String subId;
  final String language;
  final String label;
  final String url;
  final String ext;
  final bool isAutoGenerated;
  final bool isExternal;
  final String? localPath;

  SubtitleTrack copyWith({
    String? subId,
    String? language,
    String? label,
    String? url,
    String? ext,
    bool? isAutoGenerated,
    bool? isExternal,
    String? localPath,
    bool clearLocalPath = false,
  }) {
    return SubtitleTrack(
      subId: subId ?? this.subId,
      language: language ?? this.language,
      label: label ?? this.label,
      url: url ?? this.url,
      ext: ext ?? this.ext,
      isAutoGenerated: isAutoGenerated ?? this.isAutoGenerated,
      isExternal: isExternal ?? this.isExternal,
      localPath: clearLocalPath ? null : (localPath ?? this.localPath),
    );
  }

  Map<String, dynamic> toJson() {
    return <String, dynamic>{
      'subId': subId,
      'language': language,
      'label': label,
      'url': url,
      'ext': ext,
      'isAutoGenerated': isAutoGenerated,
      'isExternal': isExternal,
      'localPath': localPath,
    };
  }

  factory SubtitleTrack.fromJson(Map<String, dynamic> json) {
    return SubtitleTrack(
      subId: json['subId']?.toString() ?? '',
      language: json['language']?.toString() ?? '',
      label: json['label']?.toString() ?? '',
      url: json['url']?.toString() ?? '',
      ext: json['ext']?.toString() ?? 'srt',
      isAutoGenerated: json['isAutoGenerated'] == true,
      isExternal: json['isExternal'] == true,
      localPath: json['localPath']?.toString(),
    );
  }

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is SubtitleTrack &&
        other.subId == subId &&
        other.language == language &&
        other.label == label &&
        other.url == url &&
        other.ext == ext &&
        other.isAutoGenerated == isAutoGenerated &&
        other.isExternal == isExternal &&
        other.localPath == localPath;
  }

  @override
  int get hashCode => Object.hash(
    subId,
    language,
    label,
    url,
    ext,
    isAutoGenerated,
    isExternal,
    localPath,
  );
}
