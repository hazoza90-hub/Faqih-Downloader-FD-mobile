import 'package:faqih_downloader_mobile/core/config/app_constants.dart';
import 'package:faqih_downloader_mobile/core/models/audio_track.dart';
import 'package:faqih_downloader_mobile/core/models/clip_range.dart';
import 'package:faqih_downloader_mobile/core/models/download_status.dart';
import 'package:faqih_downloader_mobile/core/models/history_entry.dart';
import 'package:faqih_downloader_mobile/core/models/subtitle_track.dart';
import 'package:faqih_downloader_mobile/core/models/video_format_option.dart';
import 'package:faqih_downloader_mobile/core/models/youtube_stream_info.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  group('AudioTrack & SubtitleTrack', () {
    test('JSON round-trip preserves all fields', () {
      const audio = AudioTrack(
        trackId: 'aud_ar',
        formatId: '140-ar',
        language: 'ar',
        label: 'Arabic (Dubbed)',
        url: 'https://cdn.example.com/audio_ar.m4a',
        ext: 'm4a',
        filesize: 1234567,
        isOriginal: false,
        httpHeaders: <String, String>{'User-Agent': 'FD-Mobile'},
      );
      expect(AudioTrack.fromJson(audio.toJson()), equals(audio));

      const sub = SubtitleTrack(
        subId: 'sub_en',
        language: 'en',
        label: 'English',
        url: 'https://cdn.example.com/subs.srt',
        ext: 'srt',
        isAutoGenerated: true,
        isExternal: true,
        localPath: '/tmp/subs.srt',
      );
      expect(SubtitleTrack.fromJson(sub.toJson()), equals(sub));
    });
  });

  group('ClipRange', () {
    test('validates active ranges and duration bounds', () {
      const inactive = ClipRange();
      expect(inactive.isValid, isTrue);
      expect(inactive.isActive, isFalse);
      expect(inactive.durationSec, 0.0);
      expect(inactive.isValidForDuration(120.0), isTrue);

      const validClip = ClipRange(startSec: 15.0, endSec: 45.5);
      expect(validClip.isValid, isTrue);
      expect(validClip.isActive, isTrue);
      expect(validClip.durationSec, closeTo(30.5, 0.0001));
      expect(validClip.isValidForDuration(60.0), isTrue);
      expect(validClip.isValidForDuration(40.0), isFalse);

      const inverted = ClipRange(startSec: 50.0, endSec: 20.0);
      expect(inverted.isValid, isFalse);
      expect(inverted.isActive, isFalse);
      expect(inverted.isValidForDuration(100.0), isFalse);

      expect(ClipRange.fromJson(validClip.toJson()), equals(validClip));
    });
  });

  group('VideoFormatOption & YouTubeStreamInfo', () {
    test('VideoFormatOption JSON round-trip preserves nested metadata', () {
      const option = VideoFormatOption(
        formatId: '137+140',
        resolutionLabel: '1080p (Full HD)',
        height: 1080,
        width: 1920,
        fps: 60,
        ext: 'mp4',
        filesizeApprox: 52428800,
        vcodec: 'avc1.640028',
        acodec: 'mp4a.40.2',
        isProgressive: false,
        isAudioOnly: false,
        videoUrl: 'https://cdn.example.com/v1080.mp4',
        videoHeaders: <String, String>{'Referer': 'https://youtube.com'},
        audioUrl: 'https://cdn.example.com/a140.m4a',
        audioHeaders: <String, String>{'Accept': '*/*'},
        audioExt: 'm4a',
        audioSize: 4194304,
        note: '60 FPS',
        selectedAudioTrack: AudioTrack(
          trackId: 't1',
          formatId: '140',
          language: 'en',
          label: 'English',
          url: 'https://cdn.example.com/a140.m4a',
        ),
        selectedSubtitleTrack: SubtitleTrack(
          subId: 's1',
          language: 'ar',
          label: 'Arabic',
          url: 'https://cdn.example.com/ar.srt',
        ),
        clipRange: ClipRange(startSec: 10, endSec: 90),
      );

      final restored = VideoFormatOption.fromJson(option.toJson());
      expect(restored, equals(option));
    });

    test('YouTubeStreamInfo computes dual stream and JSON round-trip', () {
      const info = YouTubeStreamInfo(
        videoId: 'dQw4w9WgXcQ',
        title: 'Sample Video',
        cleanFilename: 'Sample Video.mp4',
        isProgressive: false,
        videoUrl: 'https://cdn.example.com/video.mp4',
        videoHeaders: <String, String>{'User-Agent': 'FD'},
        videoExt: 'mp4',
        videoResolution: '1080p',
        videoSize: 40000000,
        audioUrl: 'https://cdn.example.com/audio.m4a',
        audioHeaders: <String, String>{'User-Agent': 'FD'},
        audioExt: 'm4a',
        audioSize: 5000000,
        durationSec: 212,
        thumbnailUrl: 'https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg',
        isAudioOnly: false,
        platform: 'YouTube',
        webpageUrl: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ',
        audioFormatId: '140',
        audioLanguage: 'en',
        subtitleEmbedMode: AppConstants.subtitleModeHardBurn,
        clipRange: ClipRange(startSec: 5, endSec: 30),
        externalSubtitleTracks: <SubtitleTrack>[
          SubtitleTrack(
            subId: 'ext_ar',
            language: 'ar',
            label: 'Arabic External',
            url: 'https://cdn.example.com/ar.srt',
            isExternal: true,
          ),
        ],
      );

      expect(info.isDualStream, isTrue);
      expect(info.estimatedTotalSize, 45000000);

      final restored = YouTubeStreamInfo.fromJson(info.toJson());
      expect(restored, equals(info));
    });
  });

  group('HistoryEntry', () {
    test('JSON round-trip preserves timestamps, status, and metadata', () {
      final created = DateTime.utc(2026, 11, 21, 18, 0, 0);
      final completed = DateTime.utc(2026, 11, 21, 18, 5, 30);
      final entry = HistoryEntry(
        id: 'dl_101',
        url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ',
        filename: 'Sample Video [1080p].mp4',
        filePath: '/storage/emulated/0/Download/Video/Sample Video [1080p].mp4',
        category: 'Video',
        totalSize: 45000000,
        downloadedBytes: 45000000,
        status: DownloadStatus.completed,
        createdAt: created,
        completedAt: completed,
        platform: 'YouTube',
        resolution: '1080p',
      );

      final restored = HistoryEntry.fromJson(entry.toJson());
      expect(restored, equals(entry));
      expect(restored.status.isTerminal, isTrue);
      expect(restored.status.isActive, isFalse);
    });
  });
}
